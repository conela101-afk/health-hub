// Prints the approved-hosts register from scripts/validate-data.js as the markdown block kept in AI_RULES.md.
// Run: node scripts/hosts.js          (print the block)
//      node scripts/hosts.js --write  (splice it into AI_RULES.md between the markers)
// scripts/test-validate-data.js fails if AI_RULES.md and the validator differ.
const fs = require("fs");
const path = require("path");
const { SOURCE_REGISTER, TIER_LABELS } = require("./validate-data.js");
const START = "<!-- approved-hosts:start (generated by scripts/hosts.js; do not edit by hand) -->";
const END = "<!-- approved-hosts:end -->";

function block(){
  const lines = [START, ""];
  Object.keys(TIER_LABELS).forEach(t => {
    const rows = SOURCE_REGISTER.filter(r => String(r.tier) === t);
    if (!rows.length) return;
    lines.push(`**Tier ${t}: ${TIER_LABELS[t]}**`, "");
    rows.forEach(r => {
      const state = r.approved === false ? "declined or withheld" : r.approved;
      lines.push(`- \`${r.domain}\` (${state})${r.scope ? ": " + r.scope : ""}`);
    });
    lines.push("");
  });
  lines.push("Also declined (named, not hosts): Wikipedia, Medical Independent, Irish Health Pro, Limerick Leader. Tiers 1 to 5 may be a `source_url`; tier 5 never as the only source; tier 6 only on entries tagged `voluntary`; tiers 7 and 8 are links only. A host outside this list needs Elaine's approval: report it as host, owner, purpose, proposed tier and the row it is for, and do not use it.", "", END);
  return lines.join("\n");
}
function fromFile(file){
  const s = fs.readFileSync(file, "utf8");
  const a = s.indexOf(START.slice(0, 26)), b = s.indexOf(END);
  if (a < 0 || b < 0) return null;
  return { text: s.slice(a, b + END.length), a, b: b + END.length, s };
}
module.exports = { block, fromFile };
if (require.main === module){
  if (process.argv.includes("--write")){
    const file = path.join(__dirname, "..", "AI_RULES.md");
    const cur = fromFile(file);
    if (!cur){ console.error("AI_RULES.md has no approved-hosts markers"); process.exit(1); }
    fs.writeFileSync(file, cur.s.slice(0, cur.a) + block() + cur.s.slice(cur.b));
    console.log("AI_RULES.md approved-hosts block updated");
  } else console.log(block());
}
